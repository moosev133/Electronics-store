export function Icon({
  name,
  size = 20,
  ...props
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Component = icons[name as keyof typeof icons] || Sparkles;
  return <Component size={size} strokeWidth={1.65} aria-hidden="true" {...props} />;
}
