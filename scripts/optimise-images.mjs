import { readdir, writeFile } from 'node:fs/promises';
import sharp from 'sharp';
const folder = 'public/assets/products';
const responsiveImages = {};
for (const file of (await readdir(folder)).sort()) {
  if (!file.endsWith('.webp') || /-(240|480)\.webp$/.test(file)) continue;
  const metadata = await sharp(`${folder}/${file}`).metadata();
  if (!metadata.width || metadata.width < 480) continue;
  responsiveImages[`assets/products/${file}`] = metadata.width;
  for (const width of [240, 480])
    await sharp(`${folder}/${file}`)
      .resize({ width })
      .webp({ quality: 80 })
      .toFile(`${folder}/${file.replace('.webp', `-${width}.webp`)}`);
}
await sharp('public/assets/hero-living.webp')
  .resize({ width: 900 })
  .webp({ quality: 80 })
  .toFile('public/assets/hero-living-900.webp');
console.log('Responsive product derivatives and hero preview ready.');

await writeFile(
  'src/data/responsiveImages.ts',
  '// Generated by npm run images:optimise. Originals outside this map still load normally.\n' +
    'export const responsiveImages: Record<string, number> = ' +
    JSON.stringify(responsiveImages, null, 2) +
    ';\n',
);
